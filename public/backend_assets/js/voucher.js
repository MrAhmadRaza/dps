$(document).ready(function () {

    /*
    |--------------------------------------------------------------------------
    | Discount Toggle
    |--------------------------------------------------------------------------
    */

    $(document).on('change', '#discount_toggle', function () {

        const enabled = $(this).is(':checked');

        if (enabled) {
            enableDiscountMode();
        } else {
            disableDiscountMode();
        }
    });


    /*
    |--------------------------------------------------------------------------
    | Discount Amount
    |--------------------------------------------------------------------------
    */

    $(document).on('input', '#discount_amount', function () {

        if (!$('#discount_toggle').is(':checked')) {
            return;
        }

        const discountAmount =
            parseFloat($(this).val()) || 0;
        /*
        |--------------------------------------------------------------------------
        | Fee Fields
        |--------------------------------------------------------------------------
        */

        $('.fee-amount')
            .val(0)
            .prop('disabled', true)
            .prop('readonly', false);


        /*
        |--------------------------------------------------------------------------
        | Total
        |--------------------------------------------------------------------------
        */

        $('#total_amount')
            .val('0.00')
            .prop('disabled', true);


        /*
        |--------------------------------------------------------------------------
        | Due Date
        |--------------------------------------------------------------------------
        */

        $('#due_date')
            .val('')
            .prop('disabled', true);


        /*
        |--------------------------------------------------------------------------
        | Notes
        |--------------------------------------------------------------------------
        */

        $('#notes')
            .val('')
            .prop('disabled', true);
    });


    /*
    |--------------------------------------------------------------------------
    | Initial State
    |--------------------------------------------------------------------------
    */

    applyDiscountState();

});


/*
|--------------------------------------------------------------------------
| Apply Discount State
|--------------------------------------------------------------------------
*/

function applyDiscountState() {

    /*
    |--------------------------------------------------------------------------
    | Current Toggle
    |--------------------------------------------------------------------------
    */

    const toggleEnabled =
        $('#discount_toggle').is(':checked');


    /*
    |--------------------------------------------------------------------------
    | Existing Student Discount
    |--------------------------------------------------------------------------
    */

    const savedDiscount =
        Number(window.isDiscountEnabled || 0);


    /*
    |--------------------------------------------------------------------------
    | Discount ON
    |--------------------------------------------------------------------------
    */

    if (toggleEnabled || savedDiscount === 1) {

        enableDiscountMode();

        return;
    }


    /*
    |--------------------------------------------------------------------------
    | Discount OFF
    |--------------------------------------------------------------------------
    */

    disableDiscountMode();
}


/*
|--------------------------------------------------------------------------
| Enable Discount Mode
|--------------------------------------------------------------------------
*/

function enableDiscountMode() {

    $('#discount_toggle')
        .prop('checked', true);


    /*
    |--------------------------------------------------------------------------
    | Discount Section
    |--------------------------------------------------------------------------
    */

    $('#discount-section')
        .show();


    /*
    |--------------------------------------------------------------------------
    | Discount Amount
    |--------------------------------------------------------------------------
    */

    const savedAmount =
        window.discountAmount !== undefined
            ? window.discountAmount
            : $('#discount_amount').val();

    $('#discount_amount')
        .val(savedAmount || 0)
        .prop('required', true);


    /*
    |--------------------------------------------------------------------------
    | Fee Fields
    |--------------------------------------------------------------------------
    |
    | IMPORTANT:
    | Discount ON => fee fields completely disabled
    |
    */

    $('.fee-amount')
        .val(0)
        .prop('readonly', false)
        .prop('disabled', true);


    /*
    |--------------------------------------------------------------------------
    | Total
    |--------------------------------------------------------------------------
    */

    $('#total_amount')
        .val('0.00')
        .prop('disabled', true);


    /*
    |--------------------------------------------------------------------------
    | Due Date
    |--------------------------------------------------------------------------
    */

    $('#due_date')
        .val('')
        .prop('disabled', true);


    /*
    |--------------------------------------------------------------------------
    | Notes
    |--------------------------------------------------------------------------
    */

    $('#notes')
        .val('')
        .prop('disabled', true);

}


/*
|--------------------------------------------------------------------------
| Disable Discount Mode
|--------------------------------------------------------------------------
*/

function disableDiscountMode() {

    $('#discount_toggle')
        .prop('checked', false);


    /*
    |--------------------------------------------------------------------------
    | Discount Section
    |--------------------------------------------------------------------------
    */

    $('#discount-section')
        .hide();


    /*
    |--------------------------------------------------------------------------
    | Discount Amount
    |--------------------------------------------------------------------------
    */

    $('#discount_amount')
        .prop('required', false)
        .val('');


    /*
    |--------------------------------------------------------------------------
    | Restore Fee Amounts
    |--------------------------------------------------------------------------
    */

    $('.fee-amount').each(function () {

        const originalAmount =
            $(this).attr('data-original-amount') || 0;

        $(this)
            .val(originalAmount)
            .prop('disabled', false)
            .prop('readonly', false);
    });


    /*
    |--------------------------------------------------------------------------
    | Restore Total
    |--------------------------------------------------------------------------
    */

    const originalTotal =
        $('#total_amount').attr('data-original-total');

    if (originalTotal !== undefined) {

        $('#total_amount')
            .val(parseFloat(originalTotal).toFixed(2))
            .prop('disabled', false);

    } else {

        updateTotalAmount();

        $('#total_amount')
            .prop('disabled', false);
    }


    /*
    |--------------------------------------------------------------------------
    | Restore Due Date
    |--------------------------------------------------------------------------
    */

    const originalDueDate =
        $('#due_date').attr('data-original-value') || '';

    $('#due_date')
        .val(originalDueDate)
        .prop('disabled', false);


    /*
    |--------------------------------------------------------------------------
    | Restore Notes
    |--------------------------------------------------------------------------
    */

    const originalNotes =
        $('#notes').attr('data-original-value') || '';

    $('#notes')
        .val(originalNotes)
        .prop('disabled', false);



    /*
    |--------------------------------------------------------------------------
    | Voucher State
    |--------------------------------------------------------------------------
    */

    applyVoucherState();
}


/*
|--------------------------------------------------------------------------
| Apply Voucher State
|--------------------------------------------------------------------------
|
| Ye function sirf Discount OFF ke waqt voucher check karega.
|
*/

function applyVoucherState() {

    /*
    |--------------------------------------------------------------------------
    | Discount ON
    |--------------------------------------------------------------------------
    |
    | Discount state ko yahan override nahi karna.
    |
    */

    if ($('#discount_toggle').is(':checked')) {
        return;
    }


    const hasVoucher =
        $('#fee-details-section')
            .attr('data-voucher-exists') === '1';


    /*
    |--------------------------------------------------------------------------
    | Voucher EXISTS
    |--------------------------------------------------------------------------
    */

    if (hasVoucher) {

        $('.fee-amount')
            .prop('disabled', false)
            .prop('readonly', true);


        $('#due_date')
            .prop('disabled', true);


        $('#notes')
            .prop('disabled', true);

    }


    /*
    |--------------------------------------------------------------------------
    | Voucher DOES NOT EXIST
    |--------------------------------------------------------------------------
    */

    else {

        $('.fee-amount')
            .prop('disabled', false)
            .prop('readonly', false);


        $('#due_date')
            .prop('disabled', false);


        $('#notes')
            .prop('disabled', false);
    }


    /*
    |--------------------------------------------------------------------------
    | Misc Charges
    |--------------------------------------------------------------------------
    */
}


/*
|--------------------------------------------------------------------------
| Update Total Amount
|--------------------------------------------------------------------------
*/

function updateTotalAmount() {

    const hasVoucher =
        $('#fee-details-section')
            .attr('data-voucher-exists') === '1';


    if (hasVoucher) {
        return;
    }


    let total = 0;

    $('.fee-amount').each(function () {

        total += parseFloat($(this).val()) || 0;
    });


    $('#total_amount')
        .val(total.toFixed(2));
}


/*
|--------------------------------------------------------------------------
| Reset Discount
|--------------------------------------------------------------------------
*/

function resetDiscount() {

    $('#discount_toggle')
        .prop('checked', false);

    disableDiscountMode();
}